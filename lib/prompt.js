// 검색 결과를 질문 앞에 붙여 사용자 메시지를 만든다.
export function buildUserContent(question, docs) {
  const body = docs.length
    ? docs.map((d, i) => `<document index="${i + 1}" source="${d.source}">\n${d.content}\n</document>`).join("\n")
    : "(관련 문서를 찾지 못했습니다.)";
  return `<documents>\n${body}\n</documents>\n\n<question>\n${question}\n</question>`;
}
